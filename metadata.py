from mmif import DocumentTypes, AnnotationTypes

from clams.app import ClamsApp, ClamsGGUFPromptableApp
from clams.appmetadata import AppMetadata


# ----------------------------------------------------------------------------
# Gemma 4 GGUF family (llama.cpp backend, experimental)
# ----------------------------------------------------------------------------
# The instruction-tuned Gemma 4 GGUFs of ggml-org: five sizes, each at
# BF16, Q8_0 and Q4_0. Each repository holds two mmproj files and several
# draft models, so ``GEMMA4_FILES`` names the files of each model id; BF16
# variants use the BF16 projector, the others the Q8_0 one.
#
#   size       weights + mmproj (GB)
#              Q4_0     Q8_0     BF16
#   E2B         3.4      5.5     10.3
#   E4B         5.2      8.6     16.0
#   12B         7.4     12.8     24.0
#   26B-A4B    15.4     27.7     51.7    (mixture of experts, 4B active)
#   31B        18.8     33.5     62.6
#
# Revisions pinned to each repository's main-branch HEAD as of 2026-11-06.
_REVISIONS = {
    'E2B': '6938c58',
    'E4B': 'a69f018',
    '12B': '790d826',
    '26B-A4B': '9cf8c8d',
    '31B': '3d47a7e',
}
_QUANTS = ('Q8_0', 'Q4_0', 'BF16')

GEMMA4_FAMILY = {
    f'ggml-org/gemma-4-{size}-it-GGUF:{quant}': rev
    for size, rev in _REVISIONS.items() for quant in _QUANTS
}
GEMMA4_FILES = {
    f'ggml-org/gemma-4-{size}-it-GGUF:{quant}': {
        'model': f'gemma-4-{size}-it-{quant}.gguf',
        'mmproj': (f'mmproj-gemma-4-{size}-it-BF16.gguf' if quant == 'BF16'
                   else f'mmproj-gemma-4-{size}-it-Q8_0.gguf'),
    }
    for size in _REVISIONS for quant in _QUANTS
}

DEFAULT_MODEL = 'ggml-org/gemma-4-E4B-it-GGUF:Q8_0'


# DO NOT CHANGE the function name
def appmetadata() -> AppMetadata:
    metadata = AppMetadata(
        name="Gemma 4 Captioner",
        description="Applies a Gemma 4 vision-language model, run with "
                    "llama.cpp from a GGUF file, to video frames selected by "
                    "input TimeFrame annotations for prompt-driven "
                    "captioning / scene description (experimental "
                    "llama.cpp backend). Captioning is composite: the frames "
                    "sampled from a TF are fed to the model in a single "
                    "prompt and yield one caption. When `maxImagesPerPrompt` "
                    "is set, a TF with more frames than the cap is split "
                    "into several prompts and yields one caption per prompt, "
                    "all aligned to that TF. A `model` runtime parameter "
                    "selects the Gemma 4 size and quantization (default "
                    "`ggml-org/gemma-4-E4B-it-GGUF:Q8_0`); see metadata.py "
                    "for the GPU memory each needs. The app runs its own "
                    "llama-server process and needs the `llama-server` "
                    "executable (included in the container image).",
        app_license="Apache 2.0",
        identifier="gemma4-timeframe-captioner",
        url="https://github.com/clamsproject/app-gemma4-timeframe-captioner",
        analyzer_versions=GEMMA4_FAMILY,
        analyzer_license="Apache 2.0",
        # est_min = the smallest variant (E2B:Q4_0); est_typ = the default
        # (E4B:Q8_0), weights + projector + a modest context
        est_gpu_mem_min=4500,
        est_gpu_mem_typ=10000,
    )

    metadata.add_input(DocumentTypes.VideoDocument)
    in_tf = metadata.add_input(
        AnnotationTypes.TimeFrame, representatives='?', label='*')
    in_tf.add_description(
        'Labeled TimeFrame annotations selecting which video segments to caption. '
        'Frame selection within each segment is controlled by the universal '
        '`tfSamplingMode` parameter (see SDK docs). Filter by label with the '
        '`tfLabels` and `tfLabelIgnore` parameters.')

    out_td = metadata.add_output(
        DocumentTypes.TextDocument, origins='*', origination='derived')
    out_td.add_description('Caption text generated by the Gemma 4 model for '
                           'each prompt: one per processed TimeFrame, or '
                           'several when `maxImagesPerPrompt` splits a '
                           'TimeFrame. The `origins` property points to the '
                           '`TimePoint`(s) anchoring the image(s) that '
                           'caption was generated from.')
    out_align = metadata.add_output(AnnotationTypes.Alignment)
    out_align.add_description('Alignment between each parent TimeFrame and the '
                              'TextDocument(s) derived from it.')
    out_tp = metadata.add_output(
        AnnotationTypes.TimePoint, timeUnit='milliseconds', timePoint='*')
    out_tp.add_description('Optional output. Newly-created TimePoint annotations '
                           'for images sampled from a TimeFrame interval without '
                           'an existing backing TimePoint (see `tfSamplingMode`).')

    metadata.add_parameter(
        name='tfLabels', type='string', default=[], multivalued=True,
        description='Label(s) of input TimeFrame annotations to caption. By default '
                    '(`[]`), all TimeFrames are processed regardless of label. '
                    'When set, TimeFrames without a label are not processed.')
    metadata.add_parameter(
        name='tfLabelIgnore', type='string', default=[], multivalued=True,
        description='Label(s) of input TimeFrame annotations to leave out, '
                    'applied after `tfLabels`. TimeFrames without a label are '
                    'never dropped by this list.')

    ClamsGGUFPromptableApp.inject_promptable_parameters(metadata)
    for p in metadata.parameters:
        if p.name == 'model':
            # multi-member family: the SDK leaves default=None; pin the
            # recommended pick so callers can omit `model`
            p.default = DEFAULT_MODEL
        elif p.name == 'prompt':
            # content only; the output format is set by `systemPrompt`, so a
            # caller who replaces `prompt` keeps the format rules. Same
            # defaults as the Qwen3.5 captioner, for side-by-side runs.
            p.default = (
                'These frames are sampled in order from one segment of a '
                'video. Describe what is shown and quote any visible text '
                'exactly. Describe only what the frames show; do not guess '
                'the date or era.')
        elif p.name == 'systemPrompt':
            p.default = (
                'Answer in one plain-text paragraph. Do not use Markdown, '
                'headings, lists, or a separate summary.')
        elif p.name == 'maxNewTokens':
            # 512 suits the default (non-reasoning) captioning path; with
            # useReasoning=true the trace comes out of the same budget, so
            # raise this to a few thousand or the caption ends up empty
            p.default = 512

    return metadata


# DO NOT CHANGE the main block
if __name__ == '__main__':
    import sys
    metadata = appmetadata()
    for param in ClamsApp.universal_parameters:
        metadata.add_parameter(**param)
    sys.stdout.write(metadata.jsonify(pretty=True))
